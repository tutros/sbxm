//! Milestone 3 slice 2: the kits of a sandbox created from a template, and the
//! template hash (decisions 200, 209, 215).

mod common;

use common::Env;
use sbxm::config::{Profile, Template};
use sbxm::harness::Harness;
use sbxm::kit;

fn load(env: &Env, contents: &str) -> Profile {
    env.write_profile("default", contents);
    Profile::load(&env.profiles_dir(), "default").unwrap()
}

/// A profile with every build input and every runtime-only field set.
const FULL: &str = "description = \"full\"\n\
     [network]\nallow = [\"github.com\"]\ndeny = [\"telemetry.example.com\"]\n\
     [env]\nA = \"1\"\n\
     [[setup.install]]\ncommand = \"apt-get install -y jq\"\n\
     [template]\nstrict = true\nallow = [\"example.org\"]\n";

fn template(profile: &Profile) -> Template {
    profile.template.clone().unwrap()
}

#[test]
fn baked_common_mixin_has_no_install_steps_and_the_runtime_allow_list() {
    let env = Env::new();
    let profile = load(&env, FULL);

    let [(dir, common), _] = kit::all_from_template(
        "default",
        &profile,
        &template(&profile),
        "<hash>",
        Harness::Claude,
    );

    assert_eq!(dir, "common");
    insta::assert_snapshot!(common.yaml().unwrap(), @r"
    schemaVersion: '2'
    kind: mixin
    name: sbxm-common
    description: Generated by sbxm from profile 'default'. Do not edit.
    permissions:
      network:
        allow:
        - example.org
        deny:
        - telemetry.example.com
    environment:
      variables:
        A: '1'
        SBXM_CONFIG_HASH: <hash>
        SBXM_PROFILE: default
    ");
}

#[test]
fn baked_harness_mixin_keeps_the_managed_settings_step() {
    let env = Env::new();
    let dir = env.profiles_dir().join("default");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::write(dir.join("managed.json"), "{\"x\": 1}").unwrap();
    let profile = load(
        &env,
        "[harness.claude]\nmanaged_settings = \"managed.json\"\n\
         [template]\nallow = []\n",
    );

    let [_, (dir, baked)] = kit::all_from_template(
        "default",
        &profile,
        &template(&profile),
        "<hash>",
        Harness::Claude,
    );
    let [_, (_, installed)] = kit::all("default", &profile, "<hash>", Harness::Claude);

    assert_eq!(dir, "harness-claude");
    let yaml = baked.yaml().unwrap();
    assert!(yaml.contains("managed-settings.json"), "{yaml}");
    assert_eq!(yaml, installed.yaml().unwrap());
}

fn hash(env: &Env, contents: &str, harness: Harness, warm: bool) -> String {
    kit::template_hash(&load(env, contents), harness, warm)
}

#[test]
fn template_hash_is_a_full_sha256_and_stable() {
    let env = Env::new();

    let first = hash(&env, FULL, Harness::Claude, false);

    assert_eq!(first.len(), 64, "{first}");
    assert!(
        first
            .chars()
            .all(|c| c.is_ascii_digit() || ('a'..='f').contains(&c)),
        "{first}"
    );
    assert_eq!(first, hash(&env, FULL, Harness::Claude, false));
}

#[test]
fn template_hash_changes_with_each_build_input() {
    let env = Env::new();
    let base = hash(&env, FULL, Harness::Claude, false);
    let changed = [
        FULL.replace("apt-get install -y jq", "apt-get install -y yq"),
        FULL.replace("allow = [\"github.com\"]", "allow = [\"gitlab.com\"]"),
        FULL.replace("telemetry.example.com", "other.example.com"),
    ];

    for contents in &changed {
        assert_ne!(
            base,
            hash(&env, contents, Harness::Claude, false),
            "{contents}"
        );
    }
    assert_ne!(base, hash(&env, FULL, Harness::Codex, false));
    assert_ne!(base, hash(&env, FULL, Harness::Claude, true));
}

#[test]
fn template_hash_ignores_runtime_only_fields() {
    let env = Env::new();
    let base = hash(&env, FULL, Harness::Claude, false);
    let unchanged = [
        FULL.replace("description = \"full\"", "description = \"other\""),
        FULL.replace("A = \"1\"", "A = \"2\""),
        FULL.replace("strict = true", "strict = false"),
        FULL.replace("allow = [\"example.org\"]", "allow = []"),
    ];

    for contents in &unchanged {
        assert_eq!(
            base,
            hash(&env, contents, Harness::Claude, false),
            "{contents}"
        );
    }
}

#[test]
fn template_hash_ignores_managed_settings_and_instructions() {
    let env = Env::new();
    let base = hash(&env, FULL, Harness::Claude, false);
    let dir = env.profiles_dir().join("default");
    std::fs::create_dir_all(&dir).unwrap();
    let with_files = format!(
        "{FULL}[instructions]\nmandatory = \"m.md\"\n\
         [harness.claude]\nmanaged_settings = \"managed.json\"\n"
    );
    std::fs::write(dir.join("m.md"), "be careful").unwrap();
    std::fs::write(dir.join("managed.json"), "{\"x\": 1}").unwrap();

    assert_eq!(base, hash(&env, &with_files, Harness::Claude, false));
}
