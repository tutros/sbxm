//! Generates `src/status/width_table.rs`, the terminal-width table `sbxm status` measures columns
//! with (decision 185). sbxm itself has no dependency for this (decision 171(a)); this generator
//! reads the tables of a pinned `unicode-width` and writes them out as plain data, then checks
//! that the table gives the crate's width for every character and every character followed by
//! U+FE0F. Run it from the repository root when the pin is bumped:
//!
//! ```text
//! cargo run --manifest-path scripts/gen-display-width/Cargo.toml > src/status/width_table.rs
//! ```

use std::fmt::Write;

use unicode_width::UnicodeWidthStr;

const VS16: char = '\u{FE0F}';

fn width(text: &str) -> usize {
    UnicodeWidthStr::width(text)
}

fn char_width(c: char) -> usize {
    width(c.encode_utf8(&mut [0; 4]))
}

/// Every scalar value, in order.
fn chars() -> impl Iterator<Item = char> {
    (0..=0x10FFFF_u32).filter_map(char::from_u32)
}

/// Runs of consecutive characters with the same `key`, skipping those whose key is `None`.
fn runs<K: Copy + PartialEq>(key: impl Fn(char) -> Option<K>) -> Vec<(u32, u32, K)> {
    let mut out: Vec<(u32, u32, K)> = Vec::new();
    for c in chars() {
        let Some(k) = key(c) else { continue };
        let u = c as u32;
        match out.last_mut() {
            Some(run) if run.1 + 1 == u && run.2 == k => run.1 = u,
            _ => out.push((u, u, k)),
        }
    }
    out
}

/// What the generated file says a character's width is, and what U+FE0F after it does.
fn table_width(widths: &[(u32, u32, usize)], vs16: &[(u32, u32, ())], text: &str) -> usize {
    let find = |c: char| {
        let u = c as u32;
        widths
            .iter()
            .find(|r| r.0 <= u && u <= r.1)
            .map_or(1, |r| r.2)
    };
    let mut total = 0;
    let mut previous: Option<char> = None;
    for c in text.chars() {
        let w = find(c);
        if c == VS16
            && let Some(p) = previous
            && vs16.iter().any(|r| r.0 <= p as u32 && p as u32 <= r.1)
        {
            total += 2 - find(p);
        }
        total += w;
        previous = Some(c);
    }
    total
}

fn main() {
    let widths = runs(|c| Some(char_width(c)).filter(|&w| w != 1));
    let vs16 = runs(|c| (width(&format!("{c}{VS16}")) > char_width(c)).then_some(()));

    for c in chars() {
        let alone = c.to_string();
        assert_eq!(table_width(&widths, &vs16, &alone), width(&alone), "{c:?}");
        let with_vs16 = format!("{c}{VS16}");
        assert_eq!(
            table_width(&widths, &vs16, &with_vs16),
            width(&with_vs16),
            "{c:?} + U+FE0F"
        );
    }

    let mut out = String::new();
    out.push_str(
        "//! Generated by `scripts/gen-display-width` from `unicode-width` 0.2.2 (decision 185): do\n\
         //! not edit by hand. sbxm takes no dependency for terminal widths (decision 171(a)).\n\n",
    );
    out.push_str(
        "/// `(first, last, width)` for every run of characters whose terminal width isn't 1, in\n\
         /// order. A character not listed is 1 column wide.\n",
    );
    out.push_str("pub(super) const WIDTHS: &[(u32, u32, u8)] = &[\n");
    for (first, last, w) in &widths {
        writeln!(out, "    (0x{first:04X}, 0x{last:04X}, {w}),").unwrap();
    }
    out.push_str("];\n\n");
    out.push_str(
        "/// `(first, last)` for every run of characters that take 2 columns when U+FE0F (emoji\n\
         /// presentation) follows them, in order.\n",
    );
    out.push_str("pub(super) const EMOJI_PRESENTATION: &[(u32, u32)] = &[\n");
    for (first, last, ()) in &vs16 {
        writeln!(out, "    (0x{first:04X}, 0x{last:04X}),").unwrap();
    }
    out.push_str("];\n");
    print!("{out}");
}
